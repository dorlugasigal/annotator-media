#!/usr/bin/env python3
"""Generate phone.html (1080x1350) from index.html: same timeline, portrait layout and 4:5 camera shots."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
html = (root / "index.html").read_text()
swaps = [
    ('content="width=1920, height=1080"', 'content="width=1080, height=1350"'),
    ('data-width="1920" data-height="1080"', 'data-width="1080" data-height="1350"'),
    ('data-layout="desktop"', 'data-layout="phone"'),
    ('data-composition-id="main"', 'data-composition-id="main"'),
]
for old, new in swaps:
    if old not in html:
        raise SystemExit(f"index.html no longer contains {old!r}")
    html = html.replace(old, new)
for shot in ("dashboard", "smart", "focus"):
    old = f"assets/shots/{shot}-16x9.mp4"
    if old not in html:
        raise SystemExit(f"index.html no longer uses {old}")
    html = html.replace(old, f"assets/shots/{shot}-4x5.mp4")
    old_poses = f"assets/shots/{shot}-16x9.poses.js"
    if old_poses not in html:
        raise SystemExit(f"index.html no longer loads {old_poses}")
    html = html.replace(old_poses, f"assets/shots/{shot}-4x5.poses.js")
html = html.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by tools/make_phone.py from index.html. Edit index.html instead. -->", 1)
(root / "phone.html").write_text(html)
print(root / "phone.html")
